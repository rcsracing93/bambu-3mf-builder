#!/usr/bin/env python3
"""Generated diff report between two supported Bambu Studio versions.

Inputs: two options tables (from gen_bambu_options.py) and the two Studio
checkouts. Output: a markdown report with
  - settings added / removed
  - type, preset-owner, nullable changes
  - default changes
  - array sizing changes (variant set membership and stride)
  - min / max / enum value changes
  - project option list changes
  - bbs_3mf.cpp functions whose code changed (log lines ignored)

Usage: gen_version_diff.py <old.json> <new.json> <old_checkout> <new_checkout> <out.md>
"""
import json
import re
import sys
from pathlib import Path


def load(p):
    d = json.load(open(p))
    return d, {o["key"]: o for o in d["options"]}


FN_RE = re.compile(r"^\s*(?:bool|void|int|std::string|static \w+|std::pair<[^>]+>)\s+(_BBS_3MF_(?:Exporter|Importer)::\w+)\s*\(", re.M)


def functions(path):
    src = Path(path).read_text(encoding="utf-8", errors="replace")
    out, marks = {}, [(m.start(), m.group(1)) for m in FN_RE.finditer(src)]
    for i, (pos, name) in enumerate(marks):
        end = marks[i + 1][0] if i + 1 < len(marks) else len(src)
        body = src[pos:end]
        lines = [l.strip() for l in body.splitlines()
                 if l.strip() and "BOOST_LOG" not in l and not l.strip().startswith("//")
                 and "PERF_TRACE" not in l]
        # boost::format log continuation lines
        lines = [l for l in lines if not l.startswith("<< boost::format") and not l.startswith("% ")]
        key = name
        n = 2
        while key in out:
            key = "%s#%d" % (name, n); n += 1
        out[key] = "\n".join(lines)
    return out


def main(old_p, new_p, old_src, new_src, dest):
    od, o = load(old_p)
    nd, n = load(new_p)
    ot, nt = od["studio_tag"], nd["studio_tag"]
    L = ["# Studio version diff: %s -> %s" % (ot, nt), "",
         "Generated by `gen_version_diff.py` from the two options tables and the two source tags. Do not edit by hand.", ""]

    added = sorted(set(n) - set(o)); removed = sorted(set(o) - set(n))
    L += ["## Settings added (%d)" % len(added), ""]
    L += ["- `%s` (%s, %s%s)" % (k, n[k]["type"], n[k]["preset"], ", variant " + n[k]["variant"] if n[k]["variant"] else "") for k in added] or ["- none"]
    L += ["", "## Settings removed (%d)" % len(removed), ""]
    L += ["- `%s` (%s, %s)" % (k, o[k]["type"], o[k]["preset"]) for k in removed] or ["- none"]

    def section(title, field_fn):
        rows = []
        for k in sorted(set(o) & set(n)):
            a, b = field_fn(o[k]), field_fn(n[k])
            if a != b:
                rows.append("| `%s` | %s | %s |" % (k, json.dumps(a, ensure_ascii=False), json.dumps(b, ensure_ascii=False)))
        L.extend(["", "## %s (%d)" % (title, len(rows)), ""])
        if rows:
            L.extend(["| key | %s | %s |" % (ot, nt), "|---|---|---|"] + rows)
        else:
            L.append("- none")

    section("Type changes", lambda r: r["type"])
    section("Preset owner changes", lambda r: r["preset"])
    section("Nullable changes", lambda r: r["nullable"])
    section("Array sizing changes (variant set / stride)", lambda r: [r["variant"], r["variant_stride"]])
    section("Default changes", lambda r: r["default"])
    section("Min / max changes", lambda r: [r["min"], r["max"]])
    section("Enum value changes", lambda r: r.get("enum_keys"))

    po, pn = set(od["project_options"]), set(nd["project_options"])
    L += ["", "## Project options (`s_project_options`)", "",
          "- added: %s" % (", ".join("`%s`" % k for k in sorted(pn - po)) or "none"),
          "- removed: %s" % (", ".join("`%s`" % k for k in sorted(po - pn)) or "none"),
          "- count: %d -> %d" % (len(po), len(pn))]

    fo = functions(Path(old_src) / "src/libslic3r/Format/bbs_3mf.cpp")
    fn = functions(Path(new_src) / "src/libslic3r/Format/bbs_3mf.cpp")
    changed = sorted(k for k in set(fo) & set(fn) if fo[k] != fn[k])
    L += ["", "## bbs_3mf.cpp reader/writer functions", "",
          "Compared with log and trace lines removed.", "",
          "- added: %s" % (", ".join("`%s`" % k for k in sorted(set(fn) - set(fo))) or "none"),
          "- removed: %s" % (", ".join("`%s`" % k for k in sorted(set(fo) - set(fn))) or "none"),
          "- changed (%d): %s" % (len(changed), ", ".join("`%s`" % k for k in changed) or "none"),
          "", "Unchanged: %d functions." % len(set(fo) & set(fn) - set(changed))]
    Path(dest).write_text("\n".join(L) + "\n", encoding="utf-8")
    print("wrote %s: +%d -%d settings, %d bbs_3mf functions changed" % (dest, len(added), len(removed), len(changed)))


if __name__ == "__main__":
    main(*sys.argv[1:])
