#!/usr/bin/env python3
"""Builds scripts/bambu3mf/data/aliases.json (generated aliases) and references/aliases.md, and refreshes the hand-table
section of references/job-format.md.

Source of the aliases: `def->label = L("...")` in src/libslic3r/PrintConfig.cpp of each supported Studio tag.
Alias = label lowercased, every run of non-alphanumerics turned into "_", stripped.
Only print and filament options (the ones a job may set) are kept, as listed in studio/<version>/options.json.

Rebuild:  python3 tests/gen_aliases.py --src PATH/TO/SRC         (needs the two Studio source trees; writes all three files)
Docs only: python3 tests/gen_aliases.py --docs                         (from the data file; no Studio source needed)
Check:     python3 tests/gen_aliases.py --check                        (exit 1 if the docs are not current)
"""
import argparse, json, os, re, sys

H = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.normpath(os.path.join(H, ".."))
sys.path.insert(0, os.path.join(ROOT, "scripts"))

DATA = os.path.join(ROOT, "scripts", "bambu3mf", "data", "aliases.json")
ALIASES_MD = os.path.join(ROOT, "references", "aliases.md")
JOB_FORMAT = os.path.join(ROOT, "references", "job-format.md")
TAGS = {"2.8.2.61": "bs-v02.08.02.61", "2.9.1.70": "bs-v02.09.01.70", "2.9.2.62": "bs-v02.09.02.62"}   # folder under --src (bs-vTAG or vTAG)
KINDS = ("print", "filament")
BEGIN = "<!-- aliases:begin (generated by tests/gen_aliases.py; do not edit) -->"
END = "<!-- aliases:end -->"

ADD_RE = re.compile(r'\bthis->add(?:_nullable)?\(\s*"([^"]+)"')
ADD_ANY_RE = re.compile(r'=\s*this->add(?:_nullable)?\(')
LABEL_RE = re.compile(r'^\s*def->label\s*=\s*L\("((?:[^"\\]|\\.)*)"\)\s*;')


def alias_of(label):
    return re.sub(r"[^a-z0-9]+", "_", label.lower()).strip("_")


def parse_labels(cpp_path):
    """key -> label (last one wins), from def->label lines that follow `def = this->add("key", ...)`."""
    out, cur = {}, None
    with open(cpp_path, encoding="utf-8", errors="replace") as f:
        for line in f:
            s = line.strip()
            if s.startswith("//"):
                continue
            m = ADD_RE.search(line)
            if m:
                cur = m.group(1)
                continue
            if ADD_ANY_RE.search(line):
                cur = None                      # key built at run time: do not hand its label to the previous key
                continue
            m = LABEL_RE.match(line)
            if m and cur:
                out[cur] = m.group(1).replace('\\"', '"').replace("\\\\", "\\")
    return out


def hand_tables():
    from bambu3mf import job
    return job.PRINT_ALIASES, job.FILAMENT_ALIASES, job.PLATE_BED_ALIASES


def build(src):
    from bambu3mf.job import RESERVED
    from bambu3mf.profiles import ProfileSet
    hand_p, hand_f, hand_bed = hand_tables()
    hand = {"print": set(hand_p), "filament": set(hand_f) | set(hand_bed)}
    # per version: kind -> alias -> set of keys
    per = {}
    real = {}
    for ver, tag in TAGS.items():
        tree = os.path.join(src, tag) if os.path.isdir(os.path.join(src, tag)) else os.path.join(src, tag[len("bs-"):])
        labels = parse_labels(os.path.join(tree, "src", "libslic3r", "PrintConfig.cpp"))
        ps = ProfileSet(ver)
        real[ver] = set(ps.options)
        d = {k: {} for k in KINDS}
        for key, o in ps.options.items():
            if o["preset"] not in KINDS or key in RESERVED or key not in labels:
                continue
            a = alias_of(labels[key])
            if a:
                d[o["preset"]].setdefault(a, set()).add(key)
        per[ver] = d
    dropped = []
    result = {k: {} for k in KINDS}                # kind -> alias -> {key: [versions]}
    for kind in KINDS:
        names = sorted({a for ver in per for a in per[ver][kind]})
        for a in names:
            for ver in per:
                keys = per[ver][kind].get(a)
                if not keys:
                    continue
                if len(keys) > 1:
                    dropped.append({"alias": a, "kind": kind, "version": ver, "reason": "two keys", "keys": sorted(keys)})
                    continue
                key = next(iter(keys))
                if a.isdigit():
                    dropped.append({"alias": a, "kind": kind, "version": ver, "reason": "digits only, not a name", "keys": [key]})
                    continue
                if a in real[ver]:
                    dropped.append({"alias": a, "kind": kind, "version": ver, "reason": "is a real key name", "keys": [key]})
                    continue
                if a in hand[kind]:
                    dropped.append({"alias": a, "kind": kind, "version": ver, "reason": "hand table wins", "keys": [key]})
                    continue
                result[kind].setdefault(a, {}).setdefault(key, []).append(ver)
    # merge dropped rows of the same alias/kind/reason/keys across versions
    merged = {}
    for d in dropped:
        k = (d["kind"], d["alias"], d["reason"], tuple(d["keys"]))
        merged.setdefault(k, {"alias": d["alias"], "kind": d["kind"], "reason": d["reason"], "keys": d["keys"], "versions": []})["versions"].append(d["version"])
    dropped = sorted(merged.values(), key=lambda d: (d["kind"], d["alias"], d["reason"]))
    aliases = {kind: {a: [[key, vs] for key, vs in sorted(result[kind][a].items())] for a in sorted(result[kind])} for kind in KINDS}
    return {"note": "Generated by tests/gen_aliases.py from def->label in PrintConfig.cpp of each Studio tag. Do not edit. "
                    "aliases: kind -> alias -> [[studio key, [versions it applies to]], ...]. dropped: aliases left out and why.",
            "versions": list(TAGS), "aliases": aliases, "dropped": dropped}


def hand_rows():
    hand_p, hand_f, _ = hand_tables()
    rows = [(a, k, "process") for a, k in hand_p.items()] + [(a, k, "filament") for a, k in hand_f.items()]
    rows.append(("bed_temp", "the bed temperature key of the job's `plate_type` (for example `textured_plate_temp`); `plate_type` must be set", "filament"))
    rows.append(("bed_temp_first_layer", "the same key with `_initial_layer`", "filament"))
    return rows


def render_hand(data=None):
    lines = [BEGIN, "", "| You write | Studio key | Where |", "|---|---|---|"]
    for a, k, w in hand_rows():
        key = k if " " in k else "`%s`" % k
        lines.append("| `%s` | %s | %s |" % (a, key, w))
    lines += ["", "Many more names work: every print and filament setting can also be written as the label Studio shows for it, "
              "lowercased with underscores (the label \"Arc fitting\" is `arc_fitting` for `enable_arc_fitting`; \"Elephant foot compensation\" is "
              "`elephant_foot_compensation` for `elefant_foot_compensation`). Labels that are the same as the real key add nothing and are left out. The full generated list is in [aliases.md](aliases.md). "
              "An alias that would mean two different keys is not offered.", "", END]
    return "\n".join(lines)


def _vers(vs, all_vs):
    return "both" if sorted(vs) == sorted(all_vs) else ", ".join(vs) + " only"


def render_aliases_md(data):
    allv = data["versions"]
    out = ["# Generated aliases", "",
           "Generated by `tests/gen_aliases.py` from the option labels in Bambu Studio's source (%s). Do not edit by hand." % ", ".join(allv), "",
           "A label alias is the label Studio shows, lowercased, with every run of other characters turned into `_`. "
           "It is only a second spelling of the real key. Setting an alias and its real key together is an error. "
           "The short names in [job-format.md](job-format.md) come first and win over these. "
           "An alias valid in one Studio version only works only for that version.", ""]
    for kind, title in (("print", "Process settings (`[settings]` and per-object or per-part `settings`)"), ("filament", "Filament settings (`[filament.settings]`)")):
        out += ["## " + title, "", "| Alias | Studio key | Studio |", "|---|---|---|"]
        for a, ents in data["aliases"][kind].items():
            for key, vs in ents:
                out.append("| `%s` | `%s` | %s |" % (a, key, _vers(vs, allv)))
        out.append("")
    out += ["## Left out", "", "| Alias | Set | Why | Keys | Studio |", "|---|---|---|---|---|"]
    for d in data["dropped"]:
        out.append("| `%s` | %s | %s | %s | %s |" % (d["alias"], d["kind"], d["reason"], ", ".join("`%s`" % k for k in d["keys"]), _vers(d["versions"], allv)))
    out.append("")
    return "\n".join(out)


def splice(text, block):
    if BEGIN in text and END in text:
        a, b = text.index(BEGIN), text.index(END) + len(END)
        return text[:a] + block + text[b:]
    raise SystemExit("job-format.md has no alias markers")


def expected_docs():
    with open(DATA, encoding="utf-8") as f:
        data = json.load(f)
    with open(JOB_FORMAT, encoding="utf-8") as f:
        jf = f.read()
    return {JOB_FORMAT: splice(jf, render_hand()), ALIASES_MD: render_aliases_md(data)}


def write_docs():
    for p, t in expected_docs().items():
        with open(p, "w", encoding="utf-8") as f:
            f.write(t)


def stale_docs():
    bad = []
    for p, t in expected_docs().items():
        cur = open(p, encoding="utf-8").read() if os.path.exists(p) else None
        if cur != t:
            bad.append(os.path.relpath(p, ROOT))
    return bad


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", help="folder holding bs-v02.08.02.61 and bs-v02.09.01.70")
    ap.add_argument("--docs", action="store_true")
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args()
    if a.check:
        b = stale_docs()
        print("stale: " + ", ".join(b) if b else "docs current")
        sys.exit(1 if b else 0)
    if a.src:
        data = build(a.src)
        with open(DATA, "w", encoding="utf-8") as f:
            json.dump(data, f, indent=1, sort_keys=False)
            f.write("\n")
        print("aliases:", {k: len(v) for k, v in data["aliases"].items()}, "dropped:", len(data["dropped"]))
    elif not a.docs:
        ap.error("give --src, --docs or --check")
    write_docs()
