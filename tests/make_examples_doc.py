#!/usr/bin/env python3
"""Write docs/examples.md from examples/*.toml: what each job shows, the job file, and what the builder prints.
Usage: python3 tests/make_examples_doc.py [--check]   (--check exits 1 if docs/examples.md is out of date)"""
import io, os, sys, tempfile, contextlib
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
sys.path.insert(0, os.path.join(ROOT, "scripts"))
from bambu3mf.job import load_job            # noqa: E402
from bambu3mf import package, summary        # noqa: E402

ABOUT = {
    "single_p1s": "One part, one filament, P1S. The smallest useful job.",
    "single_p1p": "Same on a P1P.",
    "single_a1": "Same on an A1.",
    "single_x1c": "Same on an X1 Carbon.",
    "colors_2": "Two colors from two parts. Prime tower and purge volumes are added.",
    "colors_4": "Four colors, one part per color.",
    "colors_8": "Eight colors: eight parts, eight filament slots.",
    "modifier_negative": "A modifier part (80% infill in the lower half) and a negative part (a hole) on one body.",
    "inlay_no_penetration": "Studio 2.9.2: a body part and an inlay part, with color penetration kept inside each part (`color_penetration_cross_parts = false`).",
    "multi_plate": "Two objects on two plates.",
    "pause": "A pause at 10 mm (for example to insert a magnet).",
    "per_object_settings": "Two copies of one mesh with different walls and infill.",
    "height_ranges": "Height ranges: 0.12 mm layers for the bottom 2 mm, 0.08 mm layers and 4 walls for the top 3 mm, 0.2 mm in between.",
    "purge_matrix": "Two colors with a hand-set purge matrix: 1200 mm3 from slot 1 to slot 2 (above 900, so Studio 2.9.2) and 300 mm3 back.",
    "temperature_tower": "Temperature changes every 4 mm, 230 C down to 215 C.",
    "calibration_tower": "A ready-made calibration temperature tower, no mesh needed: five 8 mm bands from 230 C (preset 220 C + 10) down to 210 C, "
                         "each with its temperature cut into the front, a 45 and a 30 degree overhang, a 10 mm bridge and two stringing pins.",
}
ORDER = ["single_p1s", "single_p1p", "single_a1", "single_x1c", "colors_2", "colors_4", "colors_8", "modifier_negative",
         "inlay_no_penetration", "multi_plate", "pause", "per_object_settings", "height_ranges", "purge_matrix", "temperature_tower", "calibration_tower"]


def render():
    out = ["# Examples", "",
           "Generated by `tests/make_examples_doc.py` from `examples/*.toml`; do not edit by hand. Each job is built, sliced in real "
           "headless Bambu Studio and graded in CI, see [support-matrix.md](support-matrix.md). That is CI-verified, not print-tested.", "",
           "Run one: `python3 scripts/build_bambu_3mf.py examples/NAME.toml --out NAME.3mf`", ""]
    for name in ORDER:
        path = os.path.join(ROOT, "examples", name + ".toml")
        job = load_job(path)
        with tempfile.TemporaryDirectory() as d:
            s = package.build(job, os.path.join(d, name + ".3mf"))
        text = summary.format_summary(job, s)
        text = text.split("\n", 1)[1] if text.startswith("Built ") else text
        pics = sorted(f for f in os.listdir(os.path.join(ROOT, "docs", "gallery")) if f == name + ".svg" or f.startswith(name + "_plate")) \
            if os.path.isdir(os.path.join(ROOT, "docs", "gallery")) else []
        shown = ["Top view (left) and front view (right) of what Studio sliced, drawn from the G-code (`tests/make_gallery.py`):", ""] + \
                ["![%s](gallery/%s)" % (f[:-4], f) for f in pics] + [""] if pics else []
        out += ["## " + name, "", ABOUT[name], ""] + shown + ["Job (`examples/%s.toml`):" % name, "", "```toml",
                open(path).read().rstrip(), "```", "", "Builder summary:", "", "```", text.rstrip(), "```", ""]
    return "\n".join(out)


if __name__ == "__main__":
    doc = render()
    target = os.path.join(ROOT, "docs", "examples.md")
    if "--check" in sys.argv:
        sys.exit(0 if os.path.exists(target) and open(target).read() == doc else 1)
    open(target, "w").write(doc)
